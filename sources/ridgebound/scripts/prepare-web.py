"""Pinned Godot 4.6 loader extension and immutable compressed web assets.
Run after each Godot export; never relies on host Content-Encoding configuration.
"""
from pathlib import Path
import gzip, hashlib, json, re
root=Path(__file__).resolve().parents[3]
engine=root/'ridgebound/engine'
loader=engine/'ridgebound.js'
s=loader.read_text()
marker='\n\t/**\n\t * Unload the engine to free memory.'
extension='''
	// RIDGEBOUND_RESPONSE_LOADER: validated bytes supplied by our compressed asset loader.
	Engine.loadFromResponse = function (basePath, response) {
		if (loadPromise == null) {
			loadPath = basePath;
			loadPromise = Promise.resolve(response);
		}
		return loadPromise;
	};
'''
if 'RIDGEBOUND_RESPONSE_LOADER' not in s:
    assert s.count(marker)==1, 'Godot loader changed: review response extension before release'
    s=s.replace(marker, extension+marker)
    exposed="\tSafeEngine['load'] = Engine.load;"
    assert s.count(exposed)==1
    s=s.replace(exposed, exposed+"\n\tSafeEngine['loadFromResponse'] = Engine.loadFromResponse;")
    loader.write_text(s)
sha=lambda b:hashlib.sha256(b).hexdigest()
wasm=(engine/'ridgebound.wasm').read_bytes()
pck=(engine/'ridgebound.pck').read_bytes()
compressed=gzip.compress(wasm,compresslevel=9,mtime=0)
wasm_hash=sha(wasm);pck_hash=sha(pck)
gz_name=f'ridgebound.{wasm_hash[:16]}.wasm.gz'
pck_name=f'ridgebound.{pck_hash[:16]}.pck'
(engine/gz_name).write_bytes(compressed)
(engine/pck_name).write_bytes(pck)
manifest={'version':1,'engine':'4.6.3','loader':{'url':'ridgebound.js','sha256':sha(loader.read_bytes())},
'wasm':{'raw':'ridgebound.wasm','url':gz_name,'sha256':wasm_hash,'bytes':len(wasm),'compressedBytes':len(compressed),'compressedSha256':sha(compressed)},
'pack':{'url':pck_name,'sha256':pck_hash,'bytes':len(pck)}}
(engine/'assets.mjs').write_text('// Generated by sources/ridgebound/scripts/prepare-web.py\nexport default '+json.dumps(manifest,separators=(',',':'))+';\n')

# A fresh HTML entry must not pair new map coordinates with an older cached
# game pack. Stamp the changed module graph from its leaves to the entry point.
web=engine.parent
def stamp_reference(file, reference, asset):
    version=sha(asset.read_bytes())[:16]
    pattern=r"(['\"])"+re.escape(reference)+r"(?:\?v=[a-f0-9]+)?\1"
    updated,count=re.subn(pattern,lambda match:match[1]+reference+'?v='+version+match[1],file.read_text())
    assert count==1, f'Expected one reference to {reference} in {file.name}, found {count}'
    file.write_text(updated)

stamp_reference(web/'boot.mjs','./engine/assets.mjs',engine/'assets.mjs')
for name in ['world-data.mjs','ui.mjs','boot.mjs']:
    stamp_reference(web/'game.mjs','./'+name,web/name)
for name in ['game.mjs','style.css']:
    stamp_reference(web/'index.html','./'+name,web/name)
print(f'WASM {len(wasm):,} -> {len(compressed):,} bytes ({(1-len(compressed)/len(wasm))*100:.1f}% smaller)')
